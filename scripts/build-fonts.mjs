// Copies the self-hosted Manrope and Literata woff2 files (Latin, Latin-extended, Greek) from @fontsource
// and writes src/css/fonts.css with font-display: swap and the subsets' unicode-range values.
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";

const SUBSETS = ["latin", "latin-ext", "greek"];
const FAMILIES = [
  { pkg: "manrope", family: "Manrope", style: "normal", weights: [400, 500, 600, 700] },
  { pkg: "literata", family: "Literata", style: "italic", weights: [400] },
];
await mkdir("src/fonts", { recursive: true });
let css = "/* Self-hosted fonts (generated by scripts/build-fonts.mjs). Licence: SIL Open Font License 1.1. */\n";
for (const f of FAMILIES) {
  for (const w of f.weights) {
    const suffix = f.style === "italic" ? `${w}-italic` : `${w}`;
    const src = await readFile(`node_modules/@fontsource/${f.pkg}/${suffix}.css`, "utf8");
    for (const subset of SUBSETS) {
      const file = `${f.pkg}-${subset}-${w}-${f.style}.woff2`;
      // Find the unicode-range of this subset's @font-face block in the fontsource CSS.
      const block = src.split("@font-face").find((b) => b.includes(`/${file}`));
      const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
      if (!range) throw new Error(`No unicode-range for ${file}`);
      await copyFile(`node_modules/@fontsource/${f.pkg}/files/${file}`, `src/fonts/${file}`);
      css += `@font-face{font-family:"${f.family}";font-style:${f.style};font-weight:${w};font-display:swap;src:url(/fonts/${file}) format("woff2");unicode-range:${range.trim()}}\n`;
    }
  }
}
await mkdir("src/css", { recursive: true });
await writeFile("src/css/fonts.css", css);
console.log("fonts: done");
